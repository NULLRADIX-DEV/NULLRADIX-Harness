//! The Claude theme slot: `<config dir>/skills/nullradix-theme/`, a plugin folder Claude loads.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use serde_json::{Map, Value, json};

use crate::archive::{ArchiveError, Limits, read_tree};
use crate::files::{create_private_dir, write_private};

/// Folder name below `skills/`, also the plugin name.
pub const SLOT_NAME: &str = "nullradix-theme";
const MARKER_FILE: &str = ".nullradix-theme.json";
const PLUGIN_FILE: &str = ".claude-plugin/plugin.json";
const SETTINGS_FILE: &str = "hooks/nullradix-settings.ts";
const SETTINGS_HEADER: &str =
    "// Generated by NULLRADIX - do not edit. The theme source folder holds the defaults here.";
const MANAGED_BY: &str = "nullradix";
const MARKER_MAX_BYTES: u64 = 1024 * 1024;
const PATH_MAX_SEGMENTS: usize = 16;
const SEGMENT_MAX_BYTES: usize = 255;

/// A value of a theme setting as the theme sees it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SlotValue {
    Switch(bool),
    Choice(String),
}

/// The theme a slot is filled with.
#[derive(Debug, Clone, Copy)]
pub struct SlotTheme<'a> {
    pub id: &'a str,
    pub version: &'a str,
    pub name: &'a str,
    pub author: &'a str,
    pub settings: &'a BTreeMap<String, SlotValue>,
}

/// What a config folder holds at the slot.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SlotState {
    Empty,
    Managed {
        theme_id: String,
        theme_version: String,
    },
    /// A folder or file NULLRADIX did not create; it is never written or deleted.
    Foreign,
}

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct Applied {
    pub written: usize,
    pub removed: usize,
}

#[derive(Debug, thiserror::Error)]
pub enum SlotError {
    #[error("{0} is not owned by NULLRADIX")]
    Foreign(PathBuf),
    #[error("the config folder must be an absolute path: {0}")]
    Relative(PathBuf),
    #[error("the theme files are refused: {0}")]
    Source(String),
    #[error(transparent)]
    Io(#[from] io::Error),
}

fn slot_dir(config_dir: &Path) -> PathBuf {
    config_dir.join("skills").join(SLOT_NAME)
}

fn absolute(config_dir: &Path) -> Result<(), SlotError> {
    if config_dir.is_absolute() {
        Ok(())
    } else {
        Err(SlotError::Relative(config_dir.to_path_buf()))
    }
}

struct Marker {
    theme_id: String,
    theme_version: String,
    files: BTreeSet<String>,
}

fn read_marker(slot: &Path) -> Option<Marker> {
    let path = slot.join(MARKER_FILE);
    let metadata = fs::symlink_metadata(&path).ok()?;
    if !metadata.is_file() || metadata.len() > MARKER_MAX_BYTES {
        return None;
    }
    let value: Value = serde_json::from_slice(&fs::read(&path).ok()?).ok()?;
    if value.get("managedBy")?.as_str()? != MANAGED_BY {
        return None;
    }
    let files = value
        .get("files")
        .and_then(Value::as_array)
        .map_or_default(|files| {
            files
                .iter()
                .filter_map(Value::as_str)
                .filter(|path| safe_relative(path))
                .map(str::to_owned)
                .collect()
        });
    Some(Marker {
        theme_id: value.get("themeId")?.as_str()?.to_owned(),
        theme_version: value.get("themeVersion")?.as_str()?.to_owned(),
        files,
    })
}

/// Plain relative names only: what a marker on disk lists is data, never trusted.
fn safe_relative(path: &str) -> bool {
    let segments: Vec<&str> = path.split('/').collect();
    segments.len() <= PATH_MAX_SEGMENTS
        && segments.iter().all(|segment| {
            !segment.is_empty()
                && segment.len() <= SEGMENT_MAX_BYTES
                && *segment != "."
                && *segment != ".."
                && !segment.ends_with(['.', ' '])
                && !segment.contains(['\\', ':'])
                && !segment.chars().any(char::is_control)
        })
}

/// What the slot of this config folder holds; reads only.
pub fn inspect(config_dir: &Path) -> Result<SlotState, SlotError> {
    absolute(config_dir)?;
    let slot = slot_dir(config_dir);
    let metadata = match fs::symlink_metadata(&slot) {
        Ok(metadata) => metadata,
        Err(error) if error.kind() == io::ErrorKind::NotFound => return Ok(SlotState::Empty),
        Err(error) => return Err(error.into()),
    };
    if !metadata.is_dir() {
        return Ok(SlotState::Foreign);
    }
    Ok(match read_marker(&slot) {
        Some(marker) => SlotState::Managed {
            theme_id: marker.theme_id,
            theme_version: marker.theme_version,
        },
        None => SlotState::Foreign,
    })
}

/// Puts the `claude/` files of a theme, found in `source`, into the slot of `config_dir`.
pub fn apply(
    config_dir: &Path,
    source: &Path,
    theme: &SlotTheme<'_>,
    limits: Limits,
) -> Result<Applied, SlotError> {
    absolute(config_dir)?;
    let slot = slot_dir(config_dir);
    let state = inspect(config_dir)?;
    if state == SlotState::Foreign {
        return Err(SlotError::Foreign(slot));
    }
    let files = desired_files(source, theme, limits)?;
    let wanted: BTreeSet<String> = files.keys().cloned().collect();
    let marker = marker_bytes(theme, &wanted);
    let old = read_marker(&slot).map_or_default(|marker| marker.files);
    let mut applied = Applied::default();
    if state == SlotState::Empty {
        create_private_dir(&slot)?;
        // the marker comes first, so an interrupted write still leaves a folder that clears
        write_private(&slot.join(MARKER_FILE), &marker)?;
        applied.written += 1;
    }
    for (path, data) in &files {
        if write_if_changed(&slot, path, data)? {
            applied.written += 1;
        }
    }
    for stale in old.difference(&wanted) {
        if remove_file(&slot, stale)? {
            applied.removed += 1;
        }
    }
    // the marker names the new theme only once everything for it is there
    if write_if_changed(&slot, MARKER_FILE, &marker)? {
        applied.written += 1;
    }
    Ok(applied)
}

/// Removes what a previous apply put into the slot; `true` when something was removed.
pub fn clear(config_dir: &Path) -> Result<bool, SlotError> {
    absolute(config_dir)?;
    let slot = slot_dir(config_dir);
    match inspect(config_dir)? {
        SlotState::Empty => Ok(false),
        SlotState::Foreign => Err(SlotError::Foreign(slot)),
        SlotState::Managed { .. } => {
            let files = read_marker(&slot).map_or_default(|marker| marker.files);
            for path in files {
                remove_file(&slot, &path)?;
            }
            // the marker goes last: until then an interrupted clear can be repeated
            remove_file(&slot, MARKER_FILE)?;
            let _ = fs::remove_dir(&slot);
            Ok(true)
        }
    }
}

fn desired_files(
    source: &Path,
    theme: &SlotTheme<'_>,
    limits: Limits,
) -> Result<BTreeMap<String, Vec<u8>>, SlotError> {
    let entries = read_tree(source, limits).map_err(|error| match error {
        ArchiveError::Io(error) => SlotError::Io(error),
        other => SlotError::Source(other.to_string()),
    })?;
    let mut files = BTreeMap::new();
    for entry in entries {
        if !safe_relative(&entry.path) {
            return Err(SlotError::Source(format!("unsafe path {}", entry.path)));
        }
        files.insert(entry.path, entry.data);
    }
    files.insert(
        String::from(PLUGIN_FILE),
        pretty(&json!({
            "name": SLOT_NAME,
            "version": theme.version,
            "description": format!("Claude theme {} from NULLRADIX, managed by NULLRADIX", theme.name),
            "author": { "name": theme.author },
        })),
    );
    files.insert(
        String::from(SETTINGS_FILE),
        settings_module(theme.settings).into_bytes(),
    );
    Ok(files)
}

fn settings_value(settings: &BTreeMap<String, SlotValue>) -> Value {
    let map: Map<String, Value> = settings
        .iter()
        .map(|(key, value)| {
            let value = match value {
                SlotValue::Switch(on) => Value::Bool(*on),
                SlotValue::Choice(text) => Value::String(text.clone()),
            };
            (key.clone(), value)
        })
        .collect();
    Value::Object(map)
}

/// The settings file the theme's hooks import; keys sorted.
fn settings_module(settings: &BTreeMap<String, SlotValue>) -> String {
    format!(
        "{SETTINGS_HEADER}\nexport const settings: Readonly<Record<string, string | boolean>> = {}\n",
        settings_value(settings)
    )
}

fn marker_bytes(theme: &SlotTheme<'_>, files: &BTreeSet<String>) -> Vec<u8> {
    pretty(&json!({
        "managedBy": MANAGED_BY,
        "themeId": theme.id,
        "themeVersion": theme.version,
        "settings": settings_value(theme.settings),
        "files": files,
    }))
}

fn pretty(value: &Value) -> Vec<u8> {
    let mut text = value.to_string();
    text.push('\n');
    text.into_bytes()
}

/// Makes the folders below the slot real and owner-only; a link on the way is replaced.
fn prepare_parents(slot: &Path, relative: &str) -> io::Result<()> {
    let mut current = slot.to_path_buf();
    let mut segments: Vec<&str> = relative.split('/').collect();
    segments.pop();
    for segment in segments {
        current.push(segment);
        match fs::symlink_metadata(&current) {
            Ok(metadata) if metadata.is_dir() => {}
            Ok(_) => {
                remove_entry(&current)?;
                create_private_dir(&current)?;
            }
            Err(error) if error.kind() == io::ErrorKind::NotFound => create_private_dir(&current)?,
            Err(error) => return Err(error),
        }
    }
    Ok(())
}

fn write_if_changed(slot: &Path, relative: &str, data: &[u8]) -> io::Result<bool> {
    let target = slot.join(relative);
    let unchanged = fs::symlink_metadata(&target).is_ok_and(|metadata| metadata.is_file())
        && fs::read(&target).is_ok_and(|current| current == data);
    if unchanged {
        return Ok(false);
    }
    prepare_parents(slot, relative)?;
    if fs::symlink_metadata(&target).is_ok_and(|metadata| !metadata.is_file()) {
        remove_entry(&target)?;
    }
    write_private(&target, data)?;
    Ok(true)
}

/// Removes a file or link of the slot, without following links, and the folders it leaves empty.
fn remove_file(slot: &Path, relative: &str) -> io::Result<bool> {
    let target = slot.join(relative);
    match fs::symlink_metadata(&target) {
        Ok(metadata) if metadata.is_dir() => return Ok(false),
        Ok(_) => remove_entry(&target)?,
        Err(error) if error.kind() == io::ErrorKind::NotFound => return Ok(false),
        Err(error) => return Err(error),
    }
    let mut parent = target.parent();
    while let Some(dir) = parent.filter(|dir| *dir != slot && dir.starts_with(slot)) {
        if fs::remove_dir(dir).is_err() {
            break;
        }
        parent = dir.parent();
    }
    Ok(true)
}

/// A file or a link, a folder link too on Windows, never what a link points to.
fn remove_entry(path: &Path) -> io::Result<()> {
    fs::remove_file(path).or_else(|_| fs::remove_dir(path))
}

#[cfg(test)]
mod tests {
    use super::*;

    const LIMITS: Limits = Limits {
        archive: 1024 * 1024,
        file: 64 * 1024,
        entries: 20,
    };

    fn settings(palette: &str) -> BTreeMap<String, SlotValue> {
        BTreeMap::from([
            (String::from("crt"), SlotValue::Switch(true)),
            (
                String::from("palette"),
                SlotValue::Choice(palette.to_owned()),
            ),
        ])
    }

    fn theme(settings: &BTreeMap<String, SlotValue>) -> SlotTheme<'_> {
        SlotTheme {
            id: "night",
            version: "1.2.0",
            name: "Night",
            author: "Ada",
            settings,
        }
    }

    fn source() -> tempfile::TempDir {
        let dir = tempfile::tempdir().unwrap();
        fs::create_dir_all(dir.path().join("hooks")).unwrap();
        fs::write(dir.path().join("hooks/hooks.json"), r#"{"modules":[]}"#).unwrap();
        fs::write(dir.path().join("hooks/register.tsx"), "export {}").unwrap();
        dir
    }

    fn config() -> tempfile::TempDir {
        tempfile::tempdir().unwrap()
    }

    fn slot_of(config: &tempfile::TempDir) -> PathBuf {
        slot_dir(config.path())
    }

    #[test]
    fn apply_lays_out_the_plugin_marker_and_settings() {
        let (config, source, values) = (config(), source(), settings("blue"));
        let applied = apply(config.path(), source.path(), &theme(&values), LIMITS).unwrap();
        assert_eq!(
            applied,
            Applied {
                written: 5,
                removed: 0
            }
        );
        let slot = slot_of(&config);
        assert_eq!(
            fs::read_to_string(slot.join("hooks/register.tsx")).unwrap(),
            "export {}"
        );
        let plugin: Value =
            serde_json::from_slice(&fs::read(slot.join(PLUGIN_FILE)).unwrap()).unwrap();
        assert_eq!(plugin["name"], "nullradix-theme");
        assert_eq!(plugin["author"]["name"], "Ada");
        let module = fs::read_to_string(slot.join(SETTINGS_FILE)).unwrap();
        assert!(
            module.ends_with("= {\"crt\":true,\"palette\":\"blue\"}\n"),
            "{module}"
        );
        assert_eq!(
            inspect(config.path()).unwrap(),
            SlotState::Managed {
                theme_id: "night".into(),
                theme_version: "1.2.0".into()
            }
        );
        let marker: Value =
            serde_json::from_slice(&fs::read(slot.join(MARKER_FILE)).unwrap()).unwrap();
        assert_eq!(marker["files"].as_array().unwrap().len(), 4);
    }

    #[test]
    fn a_second_apply_writes_nothing_and_a_change_writes_only_the_difference() {
        let (config, source, values) = (config(), source(), settings("blue"));
        apply(config.path(), source.path(), &theme(&values), LIMITS).unwrap();
        let again = apply(config.path(), source.path(), &theme(&values), LIMITS).unwrap();
        assert_eq!(again, Applied::default());
        let red = settings("red");
        let changed = apply(config.path(), source.path(), &theme(&red), LIMITS).unwrap();
        assert_eq!(
            changed,
            Applied {
                written: 2,
                removed: 0
            }
        );
    }

    #[test]
    fn files_the_theme_dropped_are_removed_and_user_files_stay() {
        let (config, source, values) = (config(), source(), settings("blue"));
        fs::write(source.path().join("extra.ts"), "a").unwrap();
        apply(config.path(), source.path(), &theme(&values), LIMITS).unwrap();
        let slot = slot_of(&config);
        fs::write(slot.join("mine.txt"), "mine").unwrap();
        fs::remove_file(source.path().join("extra.ts")).unwrap();
        let applied = apply(config.path(), source.path(), &theme(&values), LIMITS).unwrap();
        assert_eq!(applied.removed, 1);
        assert!(!slot.join("extra.ts").exists());
        assert!(slot.join("mine.txt").is_file());
    }

    #[test]
    fn clear_removes_exactly_what_was_added() {
        let (config, source, values) = (config(), source(), settings("blue"));
        let skills = config.path().join("skills");
        fs::create_dir_all(skills.join("other")).unwrap();
        fs::write(skills.join("other/SKILL.md"), "keep").unwrap();
        apply(config.path(), source.path(), &theme(&values), LIMITS).unwrap();
        assert!(clear(config.path()).unwrap());
        assert!(!slot_of(&config).exists());
        assert_eq!(
            fs::read_to_string(skills.join("other/SKILL.md")).unwrap(),
            "keep"
        );
        assert!(!clear(config.path()).unwrap());
    }

    #[test]
    fn a_user_file_inside_the_slot_survives_clear() {
        let (config, source, values) = (config(), source(), settings("blue"));
        apply(config.path(), source.path(), &theme(&values), LIMITS).unwrap();
        let slot = slot_of(&config);
        fs::write(slot.join("mine.txt"), "mine").unwrap();
        assert!(clear(config.path()).unwrap());
        assert_eq!(fs::read_to_string(slot.join("mine.txt")).unwrap(), "mine");
        assert!(!slot.join("hooks").exists());
    }

    #[test]
    fn the_user_settings_file_is_never_touched() {
        let (config, source, values) = (config(), source(), settings("blue"));
        let user = br#"{"hooks":{},"theme":"mine","unknown":[1,2]}"#;
        fs::write(config.path().join("settings.json"), user).unwrap();
        apply(config.path(), source.path(), &theme(&values), LIMITS).unwrap();
        clear(config.path()).unwrap();
        assert_eq!(fs::read(config.path().join("settings.json")).unwrap(), user);
    }

    #[test]
    fn a_foreign_folder_is_neither_written_nor_deleted() {
        let (config, source, values) = (config(), source(), settings("blue"));
        let slot = slot_of(&config);
        fs::create_dir_all(&slot).unwrap();
        fs::write(slot.join("mine.txt"), "mine").unwrap();
        assert_eq!(inspect(config.path()).unwrap(), SlotState::Foreign);
        assert!(matches!(
            apply(config.path(), source.path(), &theme(&values), LIMITS),
            Err(SlotError::Foreign(_))
        ));
        assert!(matches!(clear(config.path()), Err(SlotError::Foreign(_))));
        assert_eq!(fs::read_to_string(slot.join("mine.txt")).unwrap(), "mine");
        fs::write(
            slot.join(MARKER_FILE),
            r#"{"managedBy":"someone","themeId":"x","themeVersion":"1"}"#,
        )
        .unwrap();
        assert_eq!(inspect(config.path()).unwrap(), SlotState::Foreign);
        fs::write(slot.join(MARKER_FILE), "{broken").unwrap();
        assert_eq!(inspect(config.path()).unwrap(), SlotState::Foreign);
    }

    #[test]
    fn a_tampered_marker_cannot_make_clear_leave_the_slot() {
        let (config, source, values) = (config(), source(), settings("blue"));
        apply(config.path(), source.path(), &theme(&values), LIMITS).unwrap();
        let victim = config.path().join("victim.txt");
        fs::write(&victim, "precious").unwrap();
        let slot = slot_of(&config);
        fs::write(
            slot.join(MARKER_FILE),
            json!({
                "managedBy": "nullradix", "themeId": "night", "themeVersion": "1.2.0",
                "files": ["../../victim.txt", "/etc/passwd", "a/../../../victim.txt", "hooks/hooks.json"],
            })
            .to_string(),
        )
        .unwrap();
        assert!(clear(config.path()).unwrap());
        assert_eq!(fs::read_to_string(&victim).unwrap(), "precious");
        assert!(!slot.join("hooks/hooks.json").exists());
    }

    #[test]
    fn unsafe_relative_paths_are_refused() {
        for bad in [
            "", "..", "a/../b", "/abs", "a//b", "a\\b", "c:x", "a/b.", "a/ ", "x/\u{7}y",
        ] {
            assert!(!safe_relative(bad), "{bad:?}");
        }
        assert!(safe_relative("hooks/register.tsx"));
        assert!(!safe_relative(&"a/".repeat(PATH_MAX_SEGMENTS + 1)));
    }

    #[test]
    fn a_relative_config_folder_is_refused() {
        let (source, values) = (source(), settings("blue"));
        let relative = Path::new("claude-config");
        assert!(matches!(inspect(relative), Err(SlotError::Relative(_))));
        assert!(matches!(
            apply(relative, source.path(), &theme(&values), LIMITS),
            Err(SlotError::Relative(_))
        ));
        assert!(matches!(clear(relative), Err(SlotError::Relative(_))));
    }

    #[test]
    fn source_files_above_the_limits_are_refused_and_nothing_is_written() {
        let (config, source, values) = (config(), source(), settings("blue"));
        let tight = Limits {
            entries: 1,
            ..LIMITS
        };
        assert!(matches!(
            apply(config.path(), source.path(), &theme(&values), tight),
            Err(SlotError::Source(_))
        ));
        fs::write(source.path().join("big.ts"), vec![b'a'; 64 * 1024 + 1]).unwrap();
        assert!(matches!(
            apply(config.path(), source.path(), &theme(&values), LIMITS),
            Err(SlotError::Source(_))
        ));
        assert!(!slot_of(&config).exists());
    }

    #[test]
    fn hidden_source_files_are_refused() {
        let (config, source, values) = (config(), source(), settings("blue"));
        fs::write(source.path().join(".nullradix-theme.json"), "{}").unwrap();
        assert!(matches!(
            apply(config.path(), source.path(), &theme(&values), LIMITS),
            Err(SlotError::Source(_))
        ));
    }

    #[test]
    fn a_missing_source_folder_is_an_io_error() {
        let (config, values) = (config(), settings("blue"));
        let missing = config.path().join("none");
        assert!(matches!(
            apply(config.path(), &missing, &theme(&values), LIMITS),
            Err(SlotError::Io(_))
        ));
    }

    #[cfg(unix)]
    #[test]
    fn a_linked_slot_is_foreign_and_a_linked_inner_folder_is_replaced() {
        use std::os::unix::fs::{PermissionsExt, symlink};
        let (config, source, values) = (config(), source(), settings("blue"));
        let outside = tempfile::tempdir().unwrap();
        fs::create_dir_all(config.path().join("skills")).unwrap();
        symlink(outside.path(), slot_of(&config)).unwrap();
        assert_eq!(inspect(config.path()).unwrap(), SlotState::Foreign);
        fs::remove_file(slot_of(&config)).unwrap();

        apply(config.path(), source.path(), &theme(&values), LIMITS).unwrap();
        let slot = slot_of(&config);
        fs::remove_dir_all(slot.join("hooks")).unwrap();
        symlink(outside.path(), slot.join("hooks")).unwrap();
        apply(config.path(), source.path(), &theme(&values), LIMITS).unwrap();
        assert!(fs::read_dir(outside.path()).unwrap().next().is_none());
        assert!(slot.join("hooks/register.tsx").is_file());
        for file in [MARKER_FILE, "hooks/register.tsx"] {
            let mode = fs::metadata(slot.join(file)).unwrap().permissions().mode();
            assert_eq!(mode & 0o077, 0, "{file} is open to others");
        }
    }
}
